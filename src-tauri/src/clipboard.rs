//! 剪贴板：轮询发现变化 → 读取并归类 → 入库 → 通知前端；以及粘贴时的写回。
//!
//! macOS 没有「剪贴板变了」的通知，只能轮询 `NSPasteboard.changeCount`（每次有人写入就 +1）。
//! 自己轮询还能顺便拿到 changeCount，用它识别「这次变化是我们自己写回造成的」，不必比对内容。

use std::path::Path;
use std::sync::Mutex;
use std::time::Duration;

use clipboard_rs::common::RustImage;
use clipboard_rs::{Clipboard, ClipboardContent, ClipboardContext, ContentFormat, RustImageData};
use objc2_app_kit::NSPasteboard;
use tauri::{AppHandle, Emitter, Manager};

use crate::config::Settings;
use crate::db::{Db, NewItem, StoredItem};
use crate::{detect, menu};

pub const UPDATED_EVENT: &str = "clipboard://updated";

const POLL_INTERVAL: Duration = Duration::from_millis(150);
/// 超大文本（比如整份日志）不收录，避免数据库膨胀。
const MAX_TEXT_BYTES: usize = 5 * 1024 * 1024;
/// 宽或高超过它的图片额外存一张缩略图给列表用（卡片约 236pt 宽，Retina 下 480px 足够清晰）。
/// 否则一屏几张 5K 截图就要解码上百 MB 像素，翻页明显掉帧。
const THUMB_MAX: u32 = 480;

/// 密码管理器等应用会给敏感内容打这些标记（nspasteboard.org 约定），带标记的一律不记录。
const SKIP_TYPES: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// 我们自己写回剪贴板后的 changeCount。用锁把「写入 + 记录计数」和轮询方的「读计数 + 比对」
/// 串起来，轮询就不可能夹在两者中间，把自己写的内容误当成新复制。
static SELF_WRITE_COUNT: Mutex<isize> = Mutex::new(-1);

fn change_count() -> isize {
    NSPasteboard::generalPasteboard().changeCount()
}

/// 启动后台轮询线程。启动时先收录一次当前剪贴板，打开面板就能看到它。
pub fn start_watcher(app: AppHandle) {
    std::thread::Builder::new()
        .name("clipboard-watcher".to_owned())
        .spawn(move || {
            let ctx = match ClipboardContext::new() {
                Ok(ctx) => ctx,
                Err(err) => {
                    log::error!("create clipboard context failed: {err}");
                    return;
                }
            };

            let mut last = change_count();
            capture(&app, &ctx);

            loop {
                std::thread::sleep(POLL_INTERVAL);
                {
                    let self_write = SELF_WRITE_COUNT.lock().unwrap_or_else(|p| p.into_inner());
                    let current = change_count();
                    if current == last {
                        continue;
                    }
                    last = current;
                    if current == *self_write {
                        continue;
                    }
                }
                capture(&app, &ctx);
            }
        })
        .expect("spawn clipboard watcher thread");
}

fn capture(app: &AppHandle, ctx: &ClipboardContext) {
    let db = app.state::<Db>();
    let item = match read_item(ctx, db.images_dir()) {
        Ok(Some(item)) => item,
        Ok(None) => return,
        Err(err) => {
            log::warn!("read clipboard failed: {err:#}");
            return;
        }
    };

    if let Err(err) = db.upsert(&item, app.state::<Settings>().get().max_items) {
        log::error!("save clipboard item failed: {err:#}");
        return;
    }
    let _ = app.emit(UPDATED_EVENT, ());
    menu::refresh_usage(app);
}

/// 读取当前剪贴板并归类。同一次复制往往同时带多种表示，优先级：文件 > 图片 > 文本。
fn read_item(ctx: &ClipboardContext, images_dir: &Path) -> anyhow::Result<Option<NewItem>> {
    let formats = ctx.available_formats().unwrap_or_default();
    if formats.iter().any(|f| SKIP_TYPES.contains(&f.as_str())) {
        return Ok(None);
    }

    if ctx.has(ContentFormat::Files) {
        if let Some(item) = files_item(clip(ctx.get_files())?) {
            return Ok(Some(item));
        }
    }

    if ctx.has(ContentFormat::Image) {
        if let Some(item) = read_image(ctx, images_dir)? {
            return Ok(Some(item));
        }
    }

    if ctx.has(ContentFormat::Text) {
        return Ok(text_item(clip(ctx.get_text())?, || read_rich(ctx)));
    }

    Ok(None)
}

/// 文本归类。能识别成链接/邮箱/颜色/路径的按识别结果归类（这类内容的格式没有意义）；
/// 否则带着 HTML / RTF 的算富文本（由 `rich` 提供），粘贴时保留格式。空白或超大文本返回 None。
fn text_item(
    text: String,
    rich: impl FnOnce() -> (Option<&'static str>, Option<String>),
) -> Option<NewItem> {
    if text.trim().is_empty() || text.len() > MAX_TEXT_BYTES {
        return None;
    }
    let (sub_kind, rich) = match detect::text_sub_kind(&text) {
        Some(kind) => (Some(kind), None),
        None => rich(),
    };
    // 去重只看纯文本：同一段字从不同 App 复制出来算一条
    let hash = hash("text", text.as_bytes());
    Some(NewItem::text(text, sub_kind, rich, hash))
}

fn files_item(paths: Vec<String>) -> Option<NewItem> {
    let paths: Vec<String> = paths.into_iter().filter(|p| !p.is_empty()).collect();
    if paths.is_empty() {
        return None;
    }
    let hash = hash("files", paths.join("\n").as_bytes());
    Some(NewItem::files(&paths, hash))
}

fn read_rich(ctx: &ClipboardContext) -> (Option<&'static str>, Option<String>) {
    if ctx.has(ContentFormat::Html) {
        if let Some(html) = ctx.get_html().ok().filter(|s| !s.trim().is_empty()) {
            return (Some("html"), Some(html));
        }
    }
    if ctx.has(ContentFormat::Rtf) {
        if let Some(rtf) = ctx.get_rich_text().ok().filter(|s| !s.trim().is_empty()) {
            return (Some("rtf"), Some(rtf));
        }
    }
    (None, None)
}

/// 图片统一存 PNG。剪贴板本身带 PNG 时直接取原始字节（不解码），
/// 否则（截图、多数 App 给的是 TIFF）交给 clipboard-rs 解码再编码。
fn read_image(ctx: &ClipboardContext, images_dir: &Path) -> anyhow::Result<Option<NewItem>> {
    let raw_png = ctx
        .get_buffer("public.png")
        .ok()
        .and_then(|bytes| png_size(&bytes).map(|size| (bytes, size)));

    let (bytes, size, decoded) = match raw_png {
        Some((bytes, size)) => (bytes, size, None),
        None => {
            let image = clip(ctx.get_image())?;
            let size = image.get_size();
            if size.0 == 0 || size.1 == 0 {
                return Ok(None);
            }
            (
                clip(image.to_png())?.get_bytes().to_vec(),
                size,
                Some(image),
            )
        }
    };

    store_image(&bytes, size, decoded, images_dir).map(Some)
}

/// 把 PNG 存进图片目录（文件名即内容哈希，同一张图只存一份），大图另存缩略图。
/// `decoded` 是已经解码好的图，有的话生成缩略图时省一次解码。
fn store_image(
    bytes: &[u8],
    size: (u32, u32),
    mut decoded: Option<RustImageData>,
    images_dir: &Path,
) -> anyhow::Result<NewItem> {
    let digest = blake3::hash(bytes).to_hex().to_string();
    let file_name = format!("{digest}.png");
    let path = images_dir.join(&file_name);
    if !path.exists() {
        std::fs::write(&path, bytes)?;
    }

    // 缩略图生成失败不影响收录，列表退回显示原图
    let thumb = if size.0 > THUMB_MAX || size.1 > THUMB_MAX {
        let thumb_name = format!("{digest}.thumb.png");
        match write_thumbnail(bytes, decoded.take(), &images_dir.join(&thumb_name)) {
            Ok(()) => Some(thumb_name),
            Err(err) => {
                log::warn!("create thumbnail failed: {err:#}");
                None
            }
        }
    } else {
        None
    };

    let file_bytes = |name: &str| std::fs::metadata(images_dir.join(name)).map_or(0, |m| m.len());
    let bytes_on_disk = file_bytes(&file_name) + thumb.as_deref().map_or(0, file_bytes);

    Ok(NewItem::image(
        file_name,
        thumb,
        size,
        bytes_on_disk,
        hash("image", digest.as_bytes()),
    ))
}

/// 同一张图再次复制时缩略图已存在，直接跳过，不重复解码。
fn write_thumbnail(png: &[u8], decoded: Option<RustImageData>, path: &Path) -> anyhow::Result<()> {
    if path.exists() {
        return Ok(());
    }
    let image = match decoded {
        Some(image) => image,
        None => clip(RustImageData::from_bytes(png))?,
    };
    let thumb = clip(image.thumbnail(THUMB_MAX, THUMB_MAX))?;
    std::fs::write(path, clip(thumb.to_png())?.get_bytes())?;
    Ok(())
}

/// 把历史记录写回系统剪贴板。
pub fn write_back(item: &StoredItem, images_dir: &Path) -> anyhow::Result<()> {
    let mut self_write = SELF_WRITE_COUNT.lock().unwrap_or_else(|p| p.into_inner());
    let ctx = clip(ClipboardContext::new())?;

    match item.kind.as_str() {
        "image" => {
            let bytes = std::fs::read(images_dir.join(&item.content))?;
            clip(ctx.set_image(clip(RustImageData::from_bytes(&bytes))?))?;
        }
        "files" => clip(ctx.set_files(item.content.lines().map(str::to_owned).collect()))?,
        _ => {
            // 富文本必须连同纯文本一起写：只写 HTML 的话，很多 App 读不到 plain text 就拒绝粘贴
            let mut contents = vec![ClipboardContent::Text(item.content.clone())];
            match (item.sub_kind.as_deref(), &item.rich) {
                (Some("html"), Some(rich)) => contents.push(ClipboardContent::Html(rich.clone())),
                (Some("rtf"), Some(rich)) => contents.push(ClipboardContent::Rtf(rich.clone())),
                _ => {}
            }
            clip(ctx.set(contents))?;
        }
    }

    *self_write = change_count();
    Ok(())
}

fn hash(kind: &str, data: &[u8]) -> String {
    let mut hasher = blake3::Hasher::new();
    hasher.update(kind.as_bytes());
    hasher.update(b":");
    hasher.update(data);
    hasher.finalize().to_hex().to_string()
}

/// 从 PNG 头（IHDR）读宽高，不解码像素。
fn png_size(bytes: &[u8]) -> Option<(u32, u32)> {
    const SIGNATURE: [u8; 8] = [0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a];
    if bytes.len() < 24 || bytes[..8] != SIGNATURE || &bytes[12..16] != b"IHDR" {
        return None;
    }
    let width = u32::from_be_bytes(bytes[16..20].try_into().ok()?);
    let height = u32::from_be_bytes(bytes[20..24].try_into().ok()?);
    (width > 0 && height > 0).then_some((width, height))
}

/// clipboard-rs 的错误是 `Box<dyn Error>`，转成 anyhow。
fn clip<T>(result: clipboard_rs::common::Result<T>) -> anyhow::Result<T> {
    result.map_err(|err| anyhow::anyhow!("{err}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn png_size_reads_ihdr() {
        let mut png = vec![0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 13];
        png.extend_from_slice(b"IHDR");
        png.extend_from_slice(&640u32.to_be_bytes());
        png.extend_from_slice(&480u32.to_be_bytes());
        assert_eq!(png_size(&png), Some((640, 480)));
        assert_eq!(png_size(b"not a png, definitely not"), None);
    }

    /// 会改写真实系统剪贴板，默认不跑：`cargo test -- --ignored`
    #[test]
    #[ignore = "touches the real system clipboard"]
    fn write_back_round_trips_each_kind() {
        let dir = std::env::temp_dir();
        let ctx = ClipboardContext::new().unwrap();
        let stored =
            |kind: &str, sub_kind: Option<&str>, content: &str, rich: Option<&str>| StoredItem {
                kind: kind.to_owned(),
                sub_kind: sub_kind.map(str::to_owned),
                content: content.to_owned(),
                rich: rich.map(str::to_owned),
            };

        // 富文本：写回后剪贴板应同时有纯文本和 HTML，再读一遍仍识别为 html
        write_back(
            &stored("text", Some("html"), "Bold text", Some("<b>Bold</b> text")),
            &dir,
        )
        .unwrap();
        let item = read_item(&ctx, &dir).unwrap().unwrap();
        assert_eq!((item.kind, item.sub_kind), ("text", Some("html")));
        assert_eq!(item.content, "Bold text");
        assert!(item.rich.unwrap().contains("<b>Bold</b>"));

        // 写回后 changeCount 已被记录，轮询会把这次变化认作自己写的
        assert_eq!(*SELF_WRITE_COUNT.lock().unwrap(), change_count());

        // 文件
        let file = dir.join("minipaste-write-back.txt");
        std::fs::write(&file, b"x").unwrap();
        let path = file.to_string_lossy().into_owned();
        write_back(&stored("files", None, &path, None), &dir).unwrap();
        let item = read_item(&ctx, &dir).unwrap().unwrap();
        assert_eq!((item.kind, item.content.as_str()), ("files", path.as_str()));
    }

    #[test]
    fn thumbnail_fits_bounds_and_keeps_aspect_ratio() {
        let mut png = Vec::new();
        image::RgbaImage::from_pixel(1200, 800, image::Rgba([90, 108, 255, 255]))
            .write_to(&mut std::io::Cursor::new(&mut png), image::ImageFormat::Png)
            .unwrap();
        let path = std::env::temp_dir().join(format!("minipaste-thumb-{}.png", std::process::id()));
        let _ = std::fs::remove_file(&path);

        write_thumbnail(&png, None, &path).unwrap();

        let thumb = std::fs::read(&path).unwrap();
        assert_eq!(png_size(&thumb), Some((THUMB_MAX, 320)));
        std::fs::remove_file(&path).unwrap();
    }

    #[test]
    fn hash_is_kind_scoped() {
        assert_eq!(hash("text", b"a"), hash("text", b"a"));
        assert_ne!(hash("text", b"a"), hash("files", b"a"));
    }
}
